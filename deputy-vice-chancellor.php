<p>Professor A K Enamul Haque, PhD, is a prominent economist with over 30 years of distinguished academic experience,
    research endeavors, and advisory roles. </p>


<p>Awarded with a PhD in Natural Resource Economics and an M.Sc. in Agricultural Economics from the University of
    Guelph, Ontario, Canada, he has etched his expertise across various domains. Professor A K Enamul Haque, PhD’s
    academic journey began at the University of Chittagong, where he earned his MSS in Economics and BSS (Hon’s) in
    Economics.
    His professional odyssey extends beyond academia, delving into the intricate intersections of economics,
    environmental sustainability, and social development.</p>

<p>Professor Haque's involvement in projects such as the economic analysis of city waste disposal in Sylhet City
    Corporation and the feasibility analysis of the Eastern Bypass Project in Dhaka showcases his commitment to
    practical problem-solving. His consultancy roles with organizations like the World Bank, IUCN, Save the Children,
    and UNDP underscore his global impact and dedication to addressing pressing issues.</p>

<p>Noteworthy are his contributions to numerous research initiatives, from evaluating the Decent Work Country Program to
    leading pre-feasibility studies for the Indian High Commission. Professor Haque's work also extends to the realm of
    education and capacity building, as evidenced by his advisory roles in the South Asian Network for Development and
    Environmental Economics (SANDEE). With a robust portfolio of over 100 publications and a penchant for community
    development, Professor Haque stands as a multifaceted academic and researcher, leaving an indelible mark on the
    economic landscape of Bangladesh and beyond.</p>

<p>Professor Haque's diverse portfolio of projects reflects not only his expertise in economic analysis but also his
    commitment to addressing critical issues ranging from climate change to water resource management. His involvement
    with the Institute of Water Modelling showcases a dedication to understanding and improving water-related
    challenges, evident in projects analyzing agricultural water demand in selected districts and contributing to the
    feasibility study for a sustainable water supply system. Furthermore, his leadership in assessing the quality of
    public expenditure in primary education with UNICEF demonstrates a holistic approach, considering the socio-economic
    implications of public policies on education.</p>

<p>Beyond his prolific research and advisory roles, Professor Haque's active participation in ecosystem services
    research with IUCN and advising on projects related to climate-resilient ecosystems and livelihoods underscores a
    broader commitment to environmental sustainability. His engagement in developing a climate and disaster
    vulnerability index for Bangladesh under UNDP funding highlights a forward-looking perspective, addressing the
    evolving challenges posed by climate change. Professor A K Enamul Haque, PhD emerges not only as an academic
    luminary but as a catalyst for positive change, leveraging his economic insights to contribute meaningfully to the
    broader social and environmental fabric.</p>

