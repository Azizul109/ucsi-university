Overview:
<h3>Cutting-edge Curriculum</h3>

<p>Our Master in International Hospitality Management is designed to provide a strong foundation in Hospitality Management. This Programme consists of 40 credit hours and is approved by the Malaysian Qualification Agency (MQA). Particularly, this course is developed for Master’s degree holders. The prospective students can get some credits exemption out of 40 credits (Conditions apply**) based on the equivalence of previous Master’s courses. Those who are currently enrolled in a Master’s degree Programme in any recognised University are also eligible for this Programme as a credit transfer student (Conditions apply**).</p>

