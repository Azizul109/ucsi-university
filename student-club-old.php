                    <h3>Student Affairs & Alumni</h3>
                    <p>
                        The Student Affairs and Alumni (SAA) office is your dedicated student representative, striving to make your academic journey as rewarding as possible. Our diverse team, hailing from various academic majors and backgrounds, is committed to being the students' voice and acting as a vital link between the student body and the university management. Our mission encompasses various essential functions, all aimed at enhancing your rights, opportunities, and overall experience, regardless of your origin. We are determined to create a level playing field for all, ensuring every student can thrive in a supportive and inclusive learning environment. <br> <br>

                        <b>Extracurricular Learning Experience Points: </b><br>
                        Extracurricular Learning Experience (ELE) highlights the importance of experiential learning (i.e. outside classroom learning), which enables students to exercise pertinent soft skills like leading and managing teams, articulating ideas, strategic planning, and evaluation skills. Students must earn 300 ELE Points to graduate from UCSI University Bangladesh Branch Campus. These points are awarded to the students when they are involved in university club activities and events. Different extra-curricular activities and involvement from students will award them with points based on the extra-curricular activities and involvement. A Student can earn 100 ELE points every year, any outstanding points won't be counted after that year ends. The total number of points is tallied and calculated for each student towards graduation.
                    </p>
