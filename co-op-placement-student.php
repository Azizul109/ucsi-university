                    <div class="panel-heading">
                        <h4 class="panel-title"> <a data-toggle="collapse" data-parent="#accordion" href="#collapseFour1" class="collapsed"> <span class="btn-title"></span> <span class="tab-title">STEP 4: Career Evaluation</span> </a></h4>
                    </div>
                    <div id="collapseFour1" class="panel-collapse collapse">
                        <div class="panel-body">
                            <p> Career evolution involves the enhancement of the necessary skill sets according to the requirements of different careers. Some careers require hard skills or technical knowledge, in which case you may want to consider attending seminars, conferences or other programmes to obtain the relevant skills.&nbsp;<br> <br> Other careers may place more emphasis on soft skills like presentation and communication skills, especially in this modern era where service is key and a company’s greatest asset is its people. This is why people skills such as leadership, listening and communication skills come in handy and other soft skills like time management, risk management, problem-solving, decision making, and effective writing skills are also good skills to have.&nbsp;<br> <br> To move your career forward, you will need to know your career goals; gathering the necessary information will help you set the right objectives. Map out your storyboard by first knowing what you want to achieve in the next 5 or 10 years. You will then need to plan how or what you need to do to get there. Begin with the end result in mind.</p>
                        </div>
                    </div>
                </div>
                <div class="panel panel-default">
                    <div class="panel-heading">
                        <h4 class="panel-title"> <a data-toggle="collapse" data-parent="#accordion" href="#collapseFive1" class="collapsed"> <span class="btn-title"></span> <span class="tab-title">STEP 5: Rating It</span> </a></h4>
                    </div>
                    <div id="collapseFive1" class="panel-collapse collapse">
                        <div class="panel-body">
                            <p>Revisions are made as necessary.</p>
                            <p>At this point, you are probably already working or have some working experience. Why is it important for you to rate yourself in terms of your career? Apart from self-improvement, doing so provides you with a good platform to gauge where you are in your career and if you are on the right track to achieve your goals. This helps you compare your expectations with what you have achieved, providing you with useful insight on the improvements needed.</p>
                            <p>To measure your performance in the workplace, you are encouraged to have a checklist based on the following areas:</p>
                            <ol>
                                <li>Duties and responsibilities given</li>
                                <li>Personal development</li>
                                <li>Work environment</li>
                                <li>Relationship with co-workers</li>
                                <li>Growth and learning opportunities</li>
                                <li>Working hours</li>
                                <li>Monetary incentives</li>
                                <li>Career advancement</li>
                                <li>Personal values</li>
                                <li>Organisational support</li>
                            </ol>
                            <p>Kindly note that each individual’s values and career expectations are different so create a set of questions on what is most important to you in your career like recognition, career advancement, learning opportunities, team work, integrity and quality of work, among others.</p>
