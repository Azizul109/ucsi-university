    <p>Attaining a university degree is every student's ultimate dream because it opens doors to career opportunities anywhere in the world. A university degree is proof of one's intellectual capacity to absorb, utilize and apply knowledge at the workplace.&nbsp;<br><br>However, in this current competitive world, knowledge and qualifications alone are insufficient to land a person that dream job or to sustain a meritorious career. Success needs more than intelligence. It requires a graduate to possess certain other personal attributes to make him/her stand out among others and be recognized as a person of substance.&nbsp;<br><br>We at UCSI University recognize the absolute importance of developing worthy personal attributes in our students to make them very attractive to employers, or to become steadfast entrepreneurs on their own. We make it our Mission to develop these characteristics in them.&nbsp;<br><br>Thus, we have developed a list of Graduate Attributes (below) which we endeavour to imbue in our students throughout the course of their studies at UCSI University, through various activities in and out of their lecture halls.&nbsp;<br><br>Our graduates will demonstrate the following attributes:</p>
