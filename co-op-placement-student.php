                        <h4 class="panel-title"> <a data-toggle="collapse" data-parent="#accordion" href="#collapseOne1" class="collapsed"> <span class="btn-title"></span> <span class="tab-title">STEP 1: Getting to know yourself</span> </a></h4>
                    </div>
                    <div id="collapseOne1" class="panel-collapse collapse">
                        <div class="panel-body">
                            <p>Everyone who has not successfully found their ideal career is out looking for it. But how does anyone conduct a successful job search? ‘Successful’ is not just finding a job, but one that fits you well. To achieve that, firstly you will need to know yourself but how are you going to do that? There are numerous facets and layers to a person’s ‘self’, but the three aspects that are relevant to match you to your ideal career are; Values, Skills, and Interests.</p>
                            <h5 class="mt-20">Values</h5>
                            <p>Values are your core beliefs and ideas of what is right and wrong.</p>
                            <h5 class="mt-20">Skills</h5>
                            <p>Skills are abilities you learn or acquire from training, and also things that you naturally do well. It often happens that we take the skills that we have for granted. The fact is that each of us has a variety of skills, but most of them go unnoticed. Do you know what skills you have? Do you know which skills you are better at?</p>
                            <h5 class="mt-20">Interests</h5>
                            <p>As explained above, values are our core beliefs; the meaning and purpose behind the things that we do. We are most likely to be comfortable and thrive in work that fits the values we strongly adhere to. On the other hand, conflict may arise when we face a work situation that clashes with our values. Consider the few samples of values related to work. Which ones are closest to your beliefs? Which are clear and precise? Which are the least important?</p>
