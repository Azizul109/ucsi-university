Overview:

<p>This programme is more than giving students the technical know-how and ideal management skills for a rewarding career in the hospitality industry. It is about preparing professionals to be objective-oriented and keeping ahead in leadership, social responsibility and ethical values to drive the industry further and greater. As such, students in this programme will be exposed to research methods, marketing and digital communications for global hospitality businesses, and data analysis interpretation for hospitality research, among others. Ideally, this programme will give students the edge to thrive in various international businesses by espousing the right aptitude towards a global career. If this appeals to you, make UCSI University your choice, and get set to take on the world.</p>

