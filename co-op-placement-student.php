                                <div class="col-md-4">
                                    <div> <img src="https://www.ucsiuniversity.edu.my/sites/default/files/todolist5.png">
                                        <p class="pt-10">Talk or have informational interviews with corporate or business people, advisors or faculty personnel with experience in the field, or of the occupation and organisation of your interest.</p>
