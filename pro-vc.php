    <p>Professor Dato’ Ir Dr Mohd Saleh Bin Jaafar is the second Pro Vice-Chancellor of UCSI University Bangladesh Branch Campus.</p>
    
    
    <p>Professor Dr Mohd. Saleh bin Jaafar is a highly accomplished individual with a remarkable journey from a challenging family background to becoming a prominent figure in the field of academia and institutional leadership. Born in Kg. Kandang, Melaka, he was the 12th child among 18 siblings to Hj. Jaafar Yon and Hjh. Embok Chik Alias. His parents were a barber and a homemaker, and his mother received recognition as an exemplary mother in 2005 from the Melaka State Government.</p>
    
    <p>Despite the tough early life, Professor Dato' Saleh persevered and excelled in his academic pursuits. He was a top student at various educational institutions, ultimately earning a BSc in Civil Engineering with honors from Michigan State University. He furthered his academic journey, obtaining an MS in Structures from the University of Michigan at Ann Arbor and a PhD from Sheffield University, UK, in 1998.</p>
    
    <p>His career has been marked by his diverse leadership roles in academia and institutions. He started his leadership journey early, heading the Civil Engineering Department at UPM within six years of returning from his PhD studies. Under his leadership, the department achieved remarkable success in research and teaching, securing substantial research grants and improving journal publications. The department earned a place in the world's top 150-200 in QS subject rankings.</p>
    
    <p>Throughout his career, Professor Dato' Saleh held various important positions, such as being the Deputy Dean, Dean of Engineering, and Deputy Vice Chancellor for Research and Innovation at UPM. He introduced and implemented strategic initiatives to enhance research and innovation, leading to increased research grants, publications, and impact factors. He integrated research across faculties, established research clusters, programs, and centers, and significantly improved laboratory accreditations.</p>
    
    <p>He also played a pivotal role in promoting innovation and showcasing UPM's expertise and technologies through initiatives like Edu-park. His leadership resulted in numerous awards and recognition for UPM, making it a leader in research and innovation in Malaysia.</p>
    
    <p>As Group CEO of UPM Holdings, Professor Dato' Saleh introduced various profitable initiatives, including the Farm to Fork concept, UPM's own Café Brands, and an International School. He also initiated land and property development programs through strategic partnerships.</p>
    
    <p>Currently serving as the Pro Vice Chancellor of UCSI University Bangladesh Branch Campus, Professor Dato' Saleh remains deeply involved in academic and institutional leadership. His extensive experience, dedication, and passion for education and innovation make him a notable figure in the field.</p>
    
