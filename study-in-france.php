                            // Function to handle modal behavior
                            function setupModal(modalId) {
                                const modal = document.getElementById(modalId);
                                const closeBtn = modal.querySelector(".close");
                                // Open the modal
                                modal.style.display = "block";
                                // Close the modal when the X is clicked
                                closeBtn.onclick = function() {
                                    modal.style.display = "none";
                                }
                                // Close the modal if user clicks outside the modal content
                                window.onclick = function(event) {
                                    if (event.target == modal) {
                                        modal.style.display = "none";
                                    }
                                }
                            }
                            // Get all modal links and assign click events
                            const links = document.querySelectorAll(".open-modal");
                            links.forEach(link => {
                                link.onclick = function(event) {
                                    event.preventDefault(); // Prevent default anchor behavior (i.e., jumping to the top)
                                    const targetModal = link.getAttribute("data-target");
                                    setupModal(targetModal);
                                }
