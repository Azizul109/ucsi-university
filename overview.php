<p> UCSI University Bangladesh Branch Campus is the 1st foreign university branch campus in Bangladesh, has its origins in
    Malaysia, where it was established in 1986. As one of Malaysia's top-ranked and largest private universities,
    UCSI has made notable strides by opening its inaugural branch in Bangladesh.We offer globally demanding 
    Undergraduate and Graduate Programmes for the students with up to 100% scholarship on merit basis.  </p>


<p> This campus provides significant advantages to Bangladeshi students, offering them the opportunity to pursue
    higher education at a globally recognised institution. Approved by the Ministries of Education in both
    Bangladesh and Malaysia, UCSI University Bangladesh Branch Campus has been operational since 2023, serving
    as a gateway to world-class education.</p>

<p> As a leading destination for higher education worldwide, UCSI's presence in Bangladesh is strategically
    designed to cater to the needs of Bangladeshi students. Students benefit from the flexibility of credit
    transfer options to the main Malaysian campus and other top global universities, facilitating their academic
    pursuits.</p>

<p> UCSI University Bangladesh Branch Campus is located at 26, Kemal Ataturk Avenue, Banani, Dhaka-1213, in a 17 
    storied commercial building with modern classrooms, lab, library, and other facilities. Some Faculty Members 
    at this university are from Malaysia and renowned foreign universities with Master’s & PhD Degrees.</p>

<p> The University is ranked 269th worldwide according to QS World University Rankings in 2026. It is also ranked 
    45th according to QS Asian University Rankings in 2025. </p>

<p> The UCSI University Bangladesh Branch Campus is committed to delivering top-notch teaching and learning
    facilities that meet international standards. The university is dedicated to investing in academic resources
    and services to enhance the student experience.</p>

<p> UCSI Bangladesh places a strong emphasis on fostering an enriching and supportive educational environment.
    Its faculty members are highly qualified, comprising a blend of internationally and nationally acclaimed
    academics dedicated to nurturing students' academic growth and success.</p>
<p> "Our global reputation ensures that our students receive a high-quality education aligned with international
    standards. Our curriculum, teaching methodologies, and faculty expertise are all benchmarked against global
    best practices, providing an education that is not only of high quality but also competitive on an international
    scale," says Chan Joe Jim, Provost of UCSI University Bangladesh Branch Campus.</p>