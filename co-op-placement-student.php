                            <p class="pt-20">After identifying your targeted job, the next step you will need to take is to prepare your resume, cover letter, and brush up on your interview skills. First timers may opt to attend the CV &amp; Cover Letter Writing Workshop, Grooming Workshop, and Interview Tips and Techniques Workshop.</p>
