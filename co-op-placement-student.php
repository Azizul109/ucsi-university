                        <h4 class="panel-title"> <a data-toggle="collapse" data-parent="#accordion" href="#collapseTwo1" class="collapsed"> <span class="btn-title"></span> <span class="tab-title">STEP 2: Mapping your blueprint</span> </a></h4>
                    </div>
                    <div id="collapseTwo1" class="panel-collapse collapse">
                        <div class="panel-body">
                            <p>To be able to draw or lay out your blueprint, there will be two crucial aspects to explore. Firstly, yourself – your interests, talents and skills, and secondly, your options; in other words, knowing what is out there for you. These two elements go hand-in-hand so you have better understanding on what to look for. You need to know what you want and to do so, you need to know what is out there – things that interest you.</p>
                            <p>Have a ‘To-do-List’ for explorative expansion in terms of industries, occupations and opportunities:</p>
                            <div class="row text-center mb-30 mt-30">
                                <div class="col-md-4">
                                    <div> <img src="https://www.ucsiuniversity.edu.my/sites/default/files/todolist1.png">
                                        <p class="pt-10">Read occupational handbooks, career books and websites, or trade magazines.</p>
                                    </div>
                                </div>
                                <div class="col-md-4">
                                    <div> <img src="https://www.ucsiuniversity.edu.my/sites/default/files/todolist2.png">
                                        <p class="pt-10">Ask, starting with your immediate circle on the possible career options out there, their career paths, and what tips and advice they would impart to the younger generation – you.</p>
                                    </div>
                                </div>
                                <div class="col-md-4">
                                    <div> <img src="https://www.ucsiuniversity.edu.my/sites/default/files/todolist3.png">
                                        <p class="pt-10">Surf the net – it is the new directory, dictionary and encyclopedia. Check out the possible fields and options for graduates in your programme major.</p>
                                    </div>
                                </div>
                            </div>
                            <div class="row text-center mb-30">
